async def test_timestamps_round_trip_as_aware_utc(database: Database) -> None:
    cid = await _conversation(database)
    async with database.session() as s, s.begin():
        row = await conv_repo.require_active(s, cid)
    assert row.created_at.utcoffset() == timedelta(0)


async def test_seq_allocation_is_race_free(database: Database) -> None:
    cid = await _conversation(database)

    async def allocate() -> int:
        async with database.session() as s, s.begin():
            return await conv_repo.allocate_seq(s, cid, utcnow())

    results = await asyncio.gather(*(allocate() for _ in range(25)))
    assert sorted(results) == list(range(1, 26))


async def test_counters_refuse_unknown_or_deleted_conversations(database: Database) -> None:
    async with database.session() as s, s.begin():
        with pytest.raises(NotFoundError):
            await conv_repo.allocate_artifact_no(s, new_id(), utcnow())
    cid = await _conversation(database)
    async with database.session() as s, s.begin():
        assert await conv_repo.tombstone(s, cid, utcnow())
        assert not await conv_repo.tombstone(s, cid, utcnow())  # already tombstoned
    async with database.session() as s, s.begin():
        with pytest.raises(NotFoundError):
            await conv_repo.allocate_seq(s, cid, utcnow())
        assert await conv_repo.get_active(s, cid) is None
        assert await conv_repo.list_tombstoned_ids(s) == [cid]


async def test_labels_resolve_only_within_their_conversation(database: Database) -> None:
    a, b = await _conversation(database), await _conversation(database)
    a1 = await _artifact(database, a)
    a2 = await _artifact(database, a)
    b1 = await _artifact(database, b)
    assert (a1.label, a2.label, b1.label) == ("img-1", "img-2", "img-1")
    async with database.session() as s, s.begin():
        found = await art_repo.get_by_label(s, a, "img-1")
        assert found is not None and found.id == a1.id
        found = await art_repo.get_by_label(s, b, "img-1")
        assert found is not None and found.id == b1.id
        assert await art_repo.get_by_label(s, b, "img-2") is None  # exists only in a


async def test_duplicate_label_in_one_conversation_rejected(database: Database) -> None:
    cid = await _conversation(database)
    await _artifact(database, cid, label="img-1")
    with pytest.raises(sa.exc.IntegrityError):
        await _artifact(database, cid, label="img-1")


async def test_lineage_queries_and_self_reference_check(database: Database) -> None:
    cid = await _conversation(database)
    src, ref, child = [await _artifact(database, cid) for _ in range(3)]
    async with database.session() as s, s.begin():
        await art_repo.add_lineage(
            s,
            child.id,
            [
                ParentRef(src.id, LineageRelation.EDIT_SOURCE),
                ParentRef(ref.id, LineageRelation.REFERENCE, 1),
            ],
        )
    async with database.session() as s, s.begin():
        parents = await art_repo.parents_of(s, child.id)
        children = await art_repo.children_of(s, src.id)
    assert [(p.artifact.id, p.relation, p.ordinal) for p in parents] == [
        (src.id, LineageRelation.EDIT_SOURCE, 0),
        (ref.id, LineageRelation.REFERENCE, 1),
    ]
    assert [c.artifact.id for c in children] == [child.id]
    with pytest.raises(sa.exc.IntegrityError):
        async with database.session() as s, s.begin():
            await art_repo.add_lineage(s, src.id, [ParentRef(src.id, LineageRelation.REFERENCE)])


async def test_deleting_a_conversation_cascades_everywhere(database: Database) -> None:
    keep = await _conversation(database)
    kept_artifact = await _artifact(database, keep)
    cid = await _conversation(database)
    parent = await _artifact(database, cid)
    child = await _artifact(database, cid)
    now = utcnow()
    async with database.session() as s, s.begin():
        message = orm.Message(
            id=new_id(), conversation_id=cid, seq=1, role=Role.USER, created_at=now
        )
        s.add(message)
        await s.flush()
        s.add(orm.MessageAttachment(message_id=message.id, artifact_id=parent.id))
        await art_repo.add_lineage(s, child.id, [ParentRef(parent.id, LineageRelation.EDIT_SOURCE)])
        job = orm.GenerationJob(
            id=new_id(),
            conversation_id=cid,
            request_message_id=message.id,
            task=JobTask.EDIT,
            backend="sdcpp",
            model="qwen-image-2.1",
            params_json={"steps": 20},
            seed=2**40,  # BIGINT
            status=JobStatus.SUCCEEDED,
            queued_at=now,
        )
        s.add(job)
        await s.flush()
        s.add(orm.JobOutput(job_id=job.id, artifact_id=child.id, seed=2**40))
    for table in ALL_TABLES:
        assert await _count(database, table) >= 1

    async with database.session() as s, s.begin():
        await conv_repo.hard_delete(s, cid)

    for table in ALL_TABLES:
        if table in (orm.Conversation, orm.Artifact):
            continue
        assert await _count(database, table) == 0, table.__tablename__
    assert await _count(database, orm.Conversation) == 1
    async with database.session() as s, s.begin():
        remaining = await art_repo.list_for_conversation(s, keep, limit=10)
    assert [a.id for a in remaining] == [kept_artifact.id]
    assert await _count(database, orm.Artifact) == 1
