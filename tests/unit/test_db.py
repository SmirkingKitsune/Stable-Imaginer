async def test_branch_migration_chains_existing_messages(tmp_path: Path) -> None:
    url = f"sqlite+aiosqlite:///{(tmp_path / 'm.sqlite3').as_posix()}"
    await asyncio.to_thread(migrate.upgrade, url, "0001")
    db = Database(url)
    try:
        async with db.engine.begin() as conn:
            now = utcnow().isoformat()
            for cid in ("a", "b"):
                await conn.exec_driver_sql(
                    "INSERT INTO conversation (id, created_at, updated_at, last_seq,"
                    " last_artifact_no) VALUES (?, ?, ?, 3, 0)",
                    (cid, now, now),
                )
                for seq in (2, 1, 3):  # insertion order must not matter
                    await conn.exec_driver_sql(
                        "INSERT INTO message (id, conversation_id, seq, role, created_at)"
                        " VALUES (?, ?, ?, 'user', ?)",
                        (f"{cid}{seq}", cid, seq, now),
                    )
    finally:
        await db.dispose()
    await asyncio.to_thread(migrate.upgrade, url)
    db = Database(url)
    try:
        async with db.engine.connect() as conn:
            rows = (
                await conn.exec_driver_sql("SELECT id, parent_id FROM message ORDER BY id")
            ).all()
    finally:
        await db.dispose()
    assert [tuple(r) for r in rows] == [
        ("a1", None),
        ("a2", "a1"),
        ("a3", "a2"),
        ("b1", None),
        ("b2", "b1"),
        ("b3", "b2"),
    ]


async def test_check_detects_drift(tmp_path: Path) -> None:
    url = f"sqlite+aiosqlite:///{(tmp_path / 'm.sqlite3').as_posix()}"
    await asyncio.to_thread(migrate.upgrade, url)
    db = Database(url)
    try:
        async with db.engine.begin() as conn:
            await conn.exec_driver_sql("CREATE TABLE stray (id INTEGER PRIMARY KEY)")
    finally:
        await db.dispose()
    with pytest.raises(AutogenerateDiffsDetected):
        await asyncio.to_thread(migrate.check, url)


