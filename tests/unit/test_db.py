async def _conversation(db: Database) -> str:
    now = utcnow()
    cid = new_id()
    async with db.session() as s, s.begin():
        await conv_repo.insert(s, orm.Conversation(id=cid, created_at=now, updated_at=now))
    return cid


async def _artifact(db: Database, cid: str, label: str | None = None) -> orm.Artifact:
    async with db.session() as s, s.begin():
        number = await conv_repo.allocate_artifact_no(s, cid, utcnow())
        row = orm.Artifact(
            id=new_id(),
            conversation_id=cid,
            kind=ArtifactKind.IMAGE,
            source=ArtifactSource.UPLOAD,
            mime="image/png",
            storage_key="artifacts/x.png",
            sha256="0" * 64,
            size_bytes=1,
            label=label or f"img-{number}",
            created_at=utcnow(),
        )
        await art_repo.insert(s, row)
    return row


async def _count(db: Database, table: type[Base]) -> int:
    async with db.session() as s, s.begin():
        return (await s.execute(sa.select(sa.func.count()).select_from(table))).scalar_one()


