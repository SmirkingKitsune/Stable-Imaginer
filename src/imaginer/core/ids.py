"""UUIDv7 identifiers (RFC 9562).

Python 3.12's ``uuid`` module has no ``uuid7``. IDs are time-ordered, so sorting by id
sorts by creation time, and B-tree inserts stay append-mostly.

Layout: 48-bit Unix milliseconds | ver(4)=7 | 12-bit counter | var(2)=0b10 | 62 random bits.
The 12-bit ``rand_a`` field is a per-millisecond counter (RFC 9562 §6.2 method 1), so IDs
generated by this process are strictly increasing even within one millisecond.
"""

import os
import threading
import time
import uuid

_MAX_COUNTER = 0xFFF
_lock = threading.Lock()
_last_ms = 0
_counter = 0


def uuid7() -> uuid.UUID:
    global _last_ms, _counter
    with _lock:
        now_ms = time.time_ns() // 1_000_000
        if now_ms > _last_ms:
            _last_ms = now_ms
            # Random start, leaving half the counter space free for same-millisecond IDs.
            _counter = int.from_bytes(os.urandom(2), "big") & 0x7FF
        else:
            # Same millisecond, or the clock went backwards: keep counting from _last_ms.
            _counter += 1
            if _counter > _MAX_COUNTER:
                _last_ms += 1
                _counter = 0
        ms, counter = _last_ms, _counter
    rand_b = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    value = ((ms & ((1 << 48) - 1)) << 80) | (0x7 << 76) | (counter << 64) | (0b10 << 62) | rand_b
    return uuid.UUID(int=value)


def new_id() -> str:
    """A new UUIDv7 as its canonical 36-character string."""
    return str(uuid7())


def uuid7_unix_ms(value: str | uuid.UUID) -> int:
    """The embedded creation timestamp (Unix ms) of a UUIDv7."""
    u = value if isinstance(value, uuid.UUID) else uuid.UUID(value)
    return u.int >> 80
